                "পাঠ্যবইয়ের অধ্যায় ২ অনুযায়ী, কম্পিউটার ভাইরাস নির্দিষ্টভাবে ৫ প্রকার—এমন কোনো তথ্য বা তালিকা নেই। তবে পাঠ্যবইয়ে ভাইরাসের কাজের ধরন ও ক্ষতিকর আচরণের ভিত্তিতে ভাইরাসের আক্রমণ এবং কিছু ক্ষতিকর ভাইরাসের উদাহরণ (যেমন: CIH, সিবিআর, স্টোন, ভিয়েনা, ট্রোজান হর্স ইত্যাদি) উল্লেখ রয়েছে।"
